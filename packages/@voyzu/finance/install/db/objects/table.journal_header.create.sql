CREATE TABLE IF NOT EXISTS journal_header (
    id                          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 10000),
    code                        TEXT NOT NULL UNIQUE,
    finance_organization_id                  BIGINT NOT NULL,
    company_code                TEXT NOT NULL,
    company_name                TEXT NOT NULL,
    document_type_code          TEXT NOT NULL,
    document_type_label         TEXT NOT NULL,
    document_id                 TEXT NOT NULL CHECK (document_id ~ '^[A-Za-z0-9_-]{1,20}$'),
    description                 TEXT NOT NULL,
    memo                        TEXT CHECK (memo IS NULL OR length(memo) <= 50),
    document_snapshot_json      jsonb_object NOT NULL DEFAULT '{}'::jsonb,
    detailed_document_snapshot_json jsonb_object NOT NULL DEFAULT '{}'::jsonb,
    posting_engine_code         TEXT NOT NULL,
    document_date               DATE NOT NULL,
    posting_date                DATE NOT NULL,
    financial_year_id           BIGINT NOT NULL,
    financial_year_code         TEXT NOT NULL,
    financial_period_id         BIGINT NOT NULL,
    financial_period_code       TEXT NOT NULL,
    base_currency_code          iso_currency_code NOT NULL,
    total_debit_base_amount     NUMERIC(18,2) CHECK (total_debit_base_amount >= 0),
    total_credit_base_amount    NUMERIC(18,2) CHECK (total_credit_base_amount >= 0),
    status                      TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'POSTED')),
    reversal_of_journal_id      BIGINT,
    reversed_by_journal_id      BIGINT,
    bank_cash_account_id        BIGINT,
    bank_cash_code              TEXT CHECK (bank_cash_code IS NULL OR bank_cash_code ~ '^[A-Z0-9_-]{1,40}$'),
    bank_cash_type              bank_cash_account_type,
    bank_cash_gl_account_id     BIGINT,
    bank_cash_gl_account_code   TEXT CHECK (bank_cash_gl_account_code IS NULL OR bank_cash_gl_account_code ~ '^[A-Z0-9_-]{1,40}$'),
    bank_cash_gl_account_name   TEXT CHECK (bank_cash_gl_account_name IS NULL OR length(bank_cash_gl_account_name) <= 50),
    bank_cash_bank_name         TEXT CHECK (bank_cash_bank_name IS NULL OR length(bank_cash_bank_name) <= 50),
    bank_cash_bank_branch_name  TEXT CHECK (bank_cash_bank_branch_name IS NULL OR length(bank_cash_bank_branch_name) <= 50),
    bank_cash_account_identifier TEXT CHECK (bank_cash_account_identifier IS NULL OR length(bank_cash_account_identifier) <= 100),
    bank_cash_cash_account_identifier TEXT CHECK (bank_cash_cash_account_identifier IS NULL OR length(bank_cash_cash_account_identifier) <= 100),
    bank_cash_tx_id             TEXT CHECK (bank_cash_tx_id IS NULL OR length(bank_cash_tx_id) <= 100),
    bank_cash_tx_code           TEXT CHECK (bank_cash_tx_code IS NULL OR length(bank_cash_tx_code) <= 100),
    bank_cash_tx_ref            TEXT CHECK (bank_cash_tx_ref IS NULL OR length(bank_cash_tx_ref) <= 100),
    bank_cash_tx_details        TEXT CHECK (bank_cash_tx_details IS NULL OR length(bank_cash_tx_details) <= 500),
    bank_cash_payment_ref       TEXT CHECK (bank_cash_payment_ref IS NULL OR length(bank_cash_payment_ref) <= 100),

    creation_date               audit_timestamp,
    creation_actor_type         actor_type,
    creation_user_id            TEXT,
    creation_mutation_id UUID,

    updated_date                audit_timestamp,
    updated_actor_type          actor_type,
    updated_user_id             TEXT,
    updated_mutation_id UUID,

    deletion_date audit_timestamp,
    deletion_actor_type actor_type,
    deletion_user_id TEXT,
    deletion_mutation_id UUID,

    CONSTRAINT fk_company           FOREIGN KEY (finance_organization_id)             REFERENCES finance_organization(id) ON DELETE CASCADE,
    CONSTRAINT fk_financial_year    FOREIGN KEY (financial_year_id)      REFERENCES fiscal_year(id),
    CONSTRAINT fk_financial_period  FOREIGN KEY (financial_period_id)    REFERENCES fiscal_period(id),
    CONSTRAINT fk_base_currency     FOREIGN KEY (base_currency_code)     REFERENCES currency(code),
    CONSTRAINT fk_reversal_of       FOREIGN KEY (reversal_of_journal_id) REFERENCES journal_header(id),
    CONSTRAINT fk_reversed_by       FOREIGN KEY (reversed_by_journal_id) REFERENCES journal_header(id),
    CONSTRAINT fk_bank_cash_control_account FOREIGN KEY (bank_cash_account_id)    REFERENCES bank_cash_control_account(id),
    CONSTRAINT fk_bank_cash_gl_account FOREIGN KEY (bank_cash_gl_account_id) REFERENCES gl_account(id),
    CONSTRAINT uq_journal_header_company_document_id UNIQUE (finance_organization_id, document_id)
);
